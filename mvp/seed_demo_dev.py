#!/usr/bin/env python3
"""Создаёт демо-задачи для кейса «1c-vibe в режиме разработчика» в Jira.

Отличие от seed_demo.py: задачи сформулированы под роль «Разработчик»
(см. 06-workflow-roli.md) — агент берёт тикет, делает ветку в git, правит
XML/BSL, прогоняет проверки и оформляет MR с пруфами; человек ревьюит.

Использование:
  python3 seed_demo_dev.py PROJECT-KEY          # создать задачи
  python3 seed_demo_dev.py PROJECT-KEY --dry    # показать, что будет создано

Тип задачи: «Задача»; если в проекте тип называется иначе, поменяй ISSUE_TYPE.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from jira_client import api, create_issue

ISSUE_TYPE = "Задача"

HOWTO = (
    "Работа по скиллу 1c-vibe-demo в режиме разработчика: ветка в git → "
    "правки XML/BSL → сборка и проверки в тестовой базе → юнит-тесты → "
    "MR с пруфами (дифф, результаты проверок). Помещение в хранилище — "
    "только по подтверждению человека.\n\n"
)

DEMO_TASKS = [
    (
        "СуммаНДС: округлять результат до копе",
        "В модуле менеджера справочника Товары функция СуммаНДС(Сумма, СтавкаНДС) "
        "возвращает дробное значение без округления: СуммаНДС(100, 20) = 20, "
        "а СуммаНДС(99.99, 20) = 19.998. Для документов нужна сумма в копейках.\n\n"
        "Ожидаемое поведение: результат округляется до двух знаков "
        "(СуммаНДС(99.99, 20) = 19.998 → 20).\n\n"
        "Критерии приёмки:\n"
        "- Когда я вызываю СуммаНДС(99.99, 20), тогда получаю 20;\n"
        "- Когда результат делится без остатка (СуммаНДС(100, 20)), тогда "
        "значение не меняется (20);\n"
        "- Существующие вызовы СуммаНДС в коде не правятся — меняется только "
        "сама функция.\n\n"
        "[Демо-задача 1c-vibe, режим разработчика: баг-фикс BSL]",
    ),
    (
        "Добавить реквизит «Штрихкод» в справочник Товары",
        "Для приёмки товара сканером нужен реквизит «Штрихкод» в справочнике "
        "Товары: строка длиной 13, фиксированная. Изменение только в "
        "метаданных, BSL-модули не трогаем.\n\n"
        "Критерии приёмки:\n"
        "- В Object.xml справочника Товары появляется атрибут «Штрихкод» "
        "(тип строка, длина 13, фиксированная);\n"
        "- Реквизиты «Наименование», «Артикул» и остальные не изменились;\n"
        "- BSL-модули не затронуты (в диффе MR только XML-метаданные).\n\n"
        "[Демо-задача 1c-vibe, режим разработчика: правка метаданных XML]",
    ),
    (
        "Функция ЦенаБезНДС + юнит-тесты в модуле менеджера",
        "В модуле менеджера справочника Товары есть функции СуммаНДС и "
        "ЦенаСНДС. Нужна обратная экспортная функция ЦенаБезНДС(Сумма, "
        "СтавкаНДС), возвращающая сумму без НДС: ЦенаБезНДС(120, 20) = 100. "
        "При отрицательной сумме или ставке — ВызватьИсключение с понятным "
        "текстом. Попутно добавить юнит-тесты на все три функции и приложить "
        "результат прогона в MR.\n\n"
        "Критерии приёмки:\n"
        "- Функция экспортная, есть комментарий в формате // Параметры: ...;\n"
        "- ЦенаБезНДС(120, 20) = 100;\n"
        "- При отрицательных параметрах выбрасывается исключение;\n"
        "- СуммаНДС и ЦенаСНДС не изменились;\n"
        "- В MR приложен отчёт прогона юнит-тестов (все зелёные).\n\n"
        "[Демо-задача 1c-vibe, режим разработчика: новый код + тесты]",
    ),
]


def main() -> None:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    dry = "--dry" in sys.argv[1:]
    if not args:
        print(__doc__)
        sys.exit(2)
    project = args[0]

    for summary, description in DEMO_TASKS:
        text = HOWTO + description
        if dry:
            print(f"[dry] {project}: {summary}")
            continue
        key = create_issue(project, summary, text, ISSUE_TYPE, labels=["1c-vibe-demo", "developer-mode"])
        print(f"Создана задача {key}: {summary}")


if __name__ == "__main__":
    main()
